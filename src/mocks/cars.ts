/**
 * Galerias adicionais (além de `imagemFull`/`imagemThumb` em `Car`).
 * Cada carro recebe entre 2 e 4 imagens. `position` começa em 1 — a
 * posição 0 é sempre a `imagemFull` do próprio carro.
 *
 * As URLs são derivadas do `toy` com sufixos `-g2`, `-g3`, `-g4` para
 * que cada slide mostre uma foto diferente do mesmo carro.
 */
const galleryPath = (toy: string, slot: number): string =>
  `https://picsum.photos/seed/${toy}-g${slot}/800/600`;

export const carImagesMock: CarImage[] = carsMock.flatMap((car) => {
  const slots = car.serieId === "serie-fast-wedge" ? 2 : 3;
  const total = slots + 1; // 3 ou 4 imagens por carro
  return Array.from({ length: total }, (_, i) => ({
    id: `${car.id}-img-${i + 1}`,
    carId: car.id,
    path: galleryPath(car.toy, i + 1),
    position: i + 1,
  }));
});
